"""
Multi-Vendor Configuration Normalization, Noise Filtering, Side-by-Side Diff Engine,
Risk Analyzer, and Rollback CLI Generator.
"""

import difflib
import hashlib
import re
from typing import Any, Dict, List, Optional, Tuple

# Regex patterns for volatile lines across Cisco IOS/XE, Juniper Junos, and Ubiquiti EdgeOS/UniFi
VOLATILE_PATTERNS = [
    re.compile(r"^!\s*Last configuration change at.*", re.IGNORECASE),
    re.compile(r"^!\s*NVRAM config last updated at.*", re.IGNORECASE),
    re.compile(r"^!\s*Time:.*", re.IGNORECASE),
    re.compile(r"^!\s*Running configuration last done at.*", re.IGNORECASE),
    re.compile(r"^Current configuration\s*:\s*\d+\s*bytes.*", re.IGNORECASE),
    re.compile(r"^Building configuration\.\.\..*", re.IGNORECASE),
    re.compile(r"^ntp clock-period\s+\d+.*", re.IGNORECASE),
    re.compile(r"^##\s*Last commit:.*", re.IGNORECASE),
    re.compile(r"^##\s*Last changed:.*", re.IGNORECASE),
    re.compile(r"^/\*\s*Warning:\s*Do not remove.*", re.IGNORECASE),
    re.compile(r"^#\s*generated by.*at\s+\d{4}-\d{2}-\d{2}.*", re.IGNORECASE),
    re.compile(r"^!\s*uptime\s+\d+.*", re.IGNORECASE),
]

RISK_RULES: List[Tuple[str, str, re.Pattern]] = [
    (
        "CRITICAL",
        "Firewall / ACL Exposure",
        re.compile(r"\b(access-list|ip access-group|permit\s+tcp\s+any\s+any|permit\s+ip\s+any\s+any|security-zone|firewall\s+name|rule\s+\d+\s+action\s+accept)\b", re.IGNORECASE),
    ),
    (
        "CRITICAL",
        "Authentication / Privilege Change",
        re.compile(r"\b(username\s+\S+|enable\s+secret|enable\s+password|system\s+login\s+user|tacacs-server|radius-server|aaa\s+new-model|line\s+vty)\b", re.IGNORECASE),
    ),
    (
        "HIGH",
        "Management / Insecure Protocol",
        re.compile(r"\b(transport\s+input\s+telnet|ip\s+http\s+server|snmp-server\s+community\s+\S+\s+RW|snmp\s+community\s+\S+\s+authorization\s+read-write)\b", re.IGNORECASE),
    ),
    (
        "HIGH",
        "Routing / BGP / OSPF Policy",
        re.compile(r"\b(router\s+(ospf|bgp|eigrp)|ip\s+route\s+|protocols\s+(bgp|ospf)|routing-options\s+static|network\s+\d+\.\d+\.\d+\.\d+)\b", re.IGNORECASE),
    ),
    (
        "MEDIUM",
        "VLAN / Switching / Trunking",
        re.compile(r"\b(switchport\s+(mode|trunk|access)|vlan\s+\d+|spanning-tree\s+|vlans\s+\S+\s+vlan-id)\b", re.IGNORECASE),
    ),
]


def is_volatile_line(line: str) -> bool:
    """Return True if a config line is volatile device noise (clock, byte count, commit timestamp)."""
    stripped = line.strip()
    for pattern in VOLATILE_PATTERNS:
        if pattern.match(stripped):
            return True
    return False


def normalize_config(config_text: str, strip_noise: bool = True) -> str:
    """Normalize line endings, trailing whitespace, and optionally strip volatile device noise."""
    if not config_text:
        return ""
    lines = config_text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    cleaned: List[str] = []
    for line in lines:
        rstripped = line.rstrip()
        if strip_noise and is_volatile_line(rstripped):
            continue
        cleaned.append(rstripped)
    # Trim leading/trailing blank lines
    while cleaned and cleaned[0] == "":
        cleaned.pop(0)
    while cleaned and cleaned[-1] == "":
        cleaned.pop()
    return "\n".join(cleaned)


def compute_config_hashes(config_text: str) -> Tuple[str, str]:
    """Return (raw_sha256, normalized_sha256) for a configuration snapshot."""
    raw_clean = normalize_config(config_text, strip_noise=False)
    norm_clean = normalize_config(config_text, strip_noise=True)
    raw_hash = hashlib.sha256(raw_clean.encode("utf-8")).hexdigest()
    norm_hash = hashlib.sha256(norm_clean.encode("utf-8")).hexdigest()
    return raw_hash, norm_hash


def classify_line_risk(line: str) -> Optional[Dict[str, str]]:
    """Inspect a changed configuration line and return risk metadata if matched."""
    for severity, category, pattern in RISK_RULES:
        if pattern.search(line):
            return {"severity": severity, "category": category}
    return None


def generate_rollback_commands(
    vendor: str, added_lines: List[str], removed_lines: List[str]
) -> List[str]:
    """
    Generate vendor-aware CLI rollback commands to revert from Current back to Last-Known-Good.
    """
    vendor_lower = (vendor or "cisco").lower()
    commands: List[str] = []

    if "juniper" in vendor_lower or "junos" in vendor_lower:
        commands.append("# Juniper Junos Rollback Procedure")
        commands.append("configure exclusive")
        for line in added_lines:
            clean = line.strip()
            if clean and not clean.startswith("#"):
                if clean.startswith("set "):
                    commands.append("delete " + clean[4:])
                else:
                    commands.append(f"# Remove added statement: {clean}")
        for line in removed_lines:
            clean = line.strip()
            if clean and not clean.startswith("#"):
                if clean.startswith("set "):
                    commands.append(clean)
                else:
                    commands.append(f"# Restore statement: {clean}")
        commands.append("commit check")
        commands.append('commit comment "Rollback to Last-Known-Good via NetGuardia"')
        return commands

    if "ubiquiti" in vendor_lower or "edgeos" in vendor_lower or "unifi" in vendor_lower:
        commands.append("# Ubiquiti EdgeOS / UniFi CLI Rollback Procedure")
        commands.append("configure")
        for line in added_lines:
            clean = line.strip()
            if clean and not clean.startswith("#") and not clean.startswith("/*"):
                if clean.startswith("set "):
                    commands.append("delete " + clean[4:])
                else:
                    commands.append(f"# Revert added line: {clean}")
        for line in removed_lines:
            clean = line.strip()
            if clean and not clean.startswith("#") and not clean.startswith("/*"):
                commands.append(clean)
        commands.append("commit")
        commands.append("save")
        commands.append("exit")
        return commands

    # Default: Cisco IOS / IOS-XE / NX-OS / ASA
    commands.append("! Cisco IOS/IOS-XE Rollback to Last-Known-Good (LKG)")
    commands.append("configure terminal")
    for line in added_lines:
        clean = line.strip()
        if clean and not clean.startswith("!"):
            if not clean.startswith("no "):
                commands.append(f"no {clean}")
            else:
                commands.append(clean[3:])
    for line in removed_lines:
        clean = line.strip()
        if clean and not clean.startswith("!"):
            commands.append(clean)
    commands.append("end")
    commands.append("write memory")
    return commands


def compare_configs(
    lkg_config: str,
    current_config: str,
    vendor: str = "Cisco",
    ignore_noise: bool = True,
    lkg_label: str = "Last-Known-Good (LKG)",
    current_label: str = "Current Config",
) -> Dict[str, Any]:
    """
    Compare Last-Known-Good (base) vs Current (target) config.
    Returns side-by-side rows, unified diff, summary counts, risk findings, and rollback CLI commands.
    """
    left_norm = normalize_config(lkg_config, strip_noise=ignore_noise)
    right_norm = normalize_config(current_config, strip_noise=ignore_noise)

    # Also compute how many noise lines were suppressed
    raw_left_lines = normalize_config(lkg_config, strip_noise=False).split("\n")
    raw_right_lines = normalize_config(current_config, strip_noise=False).split("\n")
    suppressed_noise_count = sum(1 for l in raw_left_lines if is_volatile_line(l)) + sum(
        1 for r in raw_right_lines if is_volatile_line(r)
    )

    left_lines = left_norm.split("\n") if left_norm else []
    right_lines = right_norm.split("\n") if right_norm else []

    unified_diff_lines = list(
        difflib.unified_diff(
            left_lines,
            right_lines,
            fromfile=lkg_label,
            tofile=current_label,
            lineterm="",
        )
    )

    matcher = difflib.SequenceMatcher(None, left_lines, right_lines)
    side_by_side: List[Dict[str, Any]] = []
    added_lines: List[str] = []
    removed_lines: List[str] = []
    risk_findings: List[Dict[str, Any]] = []
    seen_risks = set()

    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag == "equal":
            for offset in range(i2 - i1):
                side_by_side.append(
                    {
                        "type": "unchanged",
                        "left_line": i1 + offset + 1,
                        "left_text": left_lines[i1 + offset],
                        "right_line": j1 + offset + 1,
                        "right_text": right_lines[j1 + offset],
                        "risk": None,
                    }
                )
        elif tag == "replace":
            left_chunk = left_lines[i1:i2]
            right_chunk = right_lines[j1:j2]
            max_len = max(len(left_chunk), len(right_chunk))
            for idx in range(max_len):
                l_text = left_chunk[idx] if idx < len(left_chunk) else None
                r_text = right_chunk[idx] if idx < len(right_chunk) else None
                l_num = (i1 + idx + 1) if l_text is not None else None
                r_num = (j1 + idx + 1) if r_text is not None else None

                if l_text is not None:
                    removed_lines.append(l_text)
                if r_text is not None:
                    added_lines.append(r_text)

                risk = classify_line_risk(r_text or "") or classify_line_risk(l_text or "")
                if risk:
                    key = (risk["severity"], risk["category"], (r_text or l_text or "").strip())
                    if key not in seen_risks:
                        seen_risks.add(key)
                        risk_findings.append(
                            {
                                "severity": risk["severity"],
                                "category": risk["category"],
                                "line": (r_text or l_text or "").strip(),
                                "line_number": r_num or l_num,
                            }
                        )

                row_type = "modified" if (l_text is not None and r_text is not None) else (
                    "added" if r_text is not None else "removed"
                )
                side_by_side.append(
                    {
                        "type": row_type,
                        "left_line": l_num,
                        "left_text": l_text,
                        "right_line": r_num,
                        "right_text": r_text,
                        "risk": risk,
                    }
                )
        elif tag == "delete":
            for offset in range(i2 - i1):
                l_text = left_lines[i1 + offset]
                l_num = i1 + offset + 1
                removed_lines.append(l_text)
                risk = classify_line_risk(l_text)
                if risk:
                    key = (risk["severity"], risk["category"], l_text.strip())
                    if key not in seen_risks:
                        seen_risks.add(key)
                        risk_findings.append(
                            {
                                "severity": risk["severity"],
                                "category": risk["category"],
                                "line": l_text.strip(),
                                "line_number": l_num,
                            }
                        )
                side_by_side.append(
                    {
                        "type": "removed",
                        "left_line": l_num,
                        "left_text": l_text,
                        "right_line": None,
                        "right_text": None,
                        "risk": risk,
                    }
                )
        elif tag == "insert":
            for offset in range(j2 - j1):
                r_text = right_lines[j1 + offset]
                r_num = j1 + offset + 1
                added_lines.append(r_text)
                risk = classify_line_risk(r_text)
                if risk:
                    key = (risk["severity"], risk["category"], r_text.strip())
                    if key not in seen_risks:
                        seen_risks.add(key)
                        risk_findings.append(
                            {
                                "severity": risk["severity"],
                                "category": risk["category"],
                                "line": r_text.strip(),
                                "line_number": r_num,
                            }
                        )
                side_by_side.append(
                    {
                        "type": "added",
                        "left_line": None,
                        "left_text": None,
                        "right_line": r_num,
                        "right_text": r_text,
                        "risk": risk,
                    }
                )

    has_changes = len(added_lines) > 0 or len(removed_lines) > 0
    highest_severity = "NONE"
    if any(r["severity"] == "CRITICAL" for r in risk_findings):
        highest_severity = "CRITICAL"
    elif any(r["severity"] == "HIGH" for r in risk_findings):
        highest_severity = "HIGH"
    elif any(r["severity"] == "MEDIUM" for r in risk_findings):
        highest_severity = "MEDIUM"
    elif has_changes:
        highest_severity = "LOW"

    rollback_cli = (
        generate_rollback_commands(vendor, added_lines, removed_lines)
        if has_changes
        else ["# Configurations are identical — no rollback needed."]
    )

    return {
        "has_changes": has_changes,
        "added_count": len(added_lines),
        "removed_count": len(removed_lines),
        "suppressed_noise_lines": suppressed_noise_count if ignore_noise else 0,
        "highest_severity": highest_severity,
        "risk_findings": risk_findings,
        "unified_diff": "\n".join(unified_diff_lines),
        "side_by_side": side_by_side,
        "rollback_cli": "\n".join(rollback_cli),
    }
