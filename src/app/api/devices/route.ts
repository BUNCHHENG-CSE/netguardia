import { NextRequest } from 'next/server';
import { prisma } from '@/lib/prisma';
import { executeDeviceBackup } from '@/lib/collectorEngine';
import { jsonResponse, errorResponse, ageDays } from '@/lib/apiUtils';


export async function GET() {
  const settings = (await prisma.backupSettings.findUnique({ where: { id: 1 } })) || {
    staleBackupThresholdDays: 7,
  };
  const staleLimit = settings.staleBackupThresholdDays ?? 7;

  const rawDevices = await prisma.device.findMany({
    include: {
      credential: true,
      snapshots: {
        select: {
          id: true,
          versionNumber: true,
          normalizedHash: true,
          createdAt: true,
          isLkg: true,
        },
      },
      _count: {
        select: {
          snapshots: true,
          neighborLinks: true,
        },
      },
    },
    orderBy: { hostname: 'asc' },
  });

  const devices = rawDevices.map((dev) => {
    const ageD = ageDays(dev.lastBackupAt);
    const lkgSnap = dev.lkgSnapshotId
      ? dev.snapshots.find((s) => s.id === dev.lkgSnapshotId)
      : dev.snapshots.find((s) => s.isLkg === 1);
    const latestSnap = dev.latestSnapshotId
      ? dev.snapshots.find((s) => s.id === dev.latestSnapshotId)
      : dev.snapshots[dev.snapshots.length - 1];

    return {
      id: dev.id,
      hostname: dev.hostname,
      ip_address: dev.ipAddress,
      ssh_port: dev.sshPort,
      vendor: dev.vendor,
      model: dev.model,
      os_type: dev.osType,
      role: dev.role,
      site: dev.site,
      credential_id: dev.credentialId,
      credential_name: dev.credential?.name || null,
      credential_protocol: dev.credential?.protocol || null,
      is_simulated: dev.isSimulated === 1,
      status: dev.status,
      drift_detected: dev.driftDetected === 1,
      lkg_snapshot_id: dev.lkgSnapshotId,
      latest_snapshot_id: dev.latestSnapshotId,
      lkg_version: lkgSnap?.versionNumber ?? null,
      lkg_hash: lkgSnap?.normalizedHash ?? null,
      lkg_created_at: lkgSnap?.createdAt ?? null,
      latest_version: latestSnap?.versionNumber ?? null,
      latest_hash: latestSnap?.normalizedHash ?? null,
      last_backup_at: dev.lastBackupAt,
      last_verified_at: dev.lastVerifiedAt,
      backup_age_days: ageD,
      is_stale: ageD > staleLimit,
      snapshot_count: dev._count.snapshots,
      neighbor_count: dev._count.neighborLinks,
    };
  });

  return jsonResponse(devices);
}

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const {
      hostname,
      ip_address,
      ssh_port = 22,
      vendor = 'Cisco',
      model = 'Catalyst C9300-24T',
      os_type = 'Cisco IOS-XE 17.9',
      role = 'Access Switch',
      site = 'HQ-Campus (Austin)',
      credential_id = 1,
      is_simulated = true,
      uplink_hostname = 'hq-dist-sw01',
      uplink_local_port = 'GigabitEthernet1/0/24',
      uplink_remote_port = 'GigabitEthernet1/0/10',
    } = body;

    if (!hostname || !ip_address) {
      return errorResponse('Hostname and IP address are required', 400);
    }

    const nowIso = new Date().toISOString();
    const v = vendor.toLowerCase();
    const uplinkHost = uplink_hostname || 'hq-core-sw01';
    const localP = uplink_local_port || 'GigabitEthernet1/0/24';
    const remoteP = uplink_remote_port || 'GigabitEthernet1/0/15';

    let simCfg = '';
    let simNeigh = '';

    if (v.includes('juniper')) {
      simCfg = `## Last commit: ${nowIso} by netops\nset version 22.4R3\nset system host-name ${hostname}\nset system services ssh root-login deny\nset interfaces ${localP} description "UPLINK-TO-${uplinkHost.toUpperCase()}"\nset protocols lldp interface all\nset vlans CORP_WORKSTATIONS vlan-id 10`;
      simNeigh = `Local Interface    Parent Interface    Chassis Id          Port info          System Name\n${localP.padEnd(18)} -                   00:1c:73:aa:bb:cc   ${remoteP.padEnd(18)} ${uplinkHost}`;
    } else if (v.includes('ubiquiti') || v.includes('unifi')) {
      simCfg = `# generated by EdgeOS v2.0.9 at ${nowIso}\nset system host-name ${hostname}\nset interfaces switch switch0 description '${site} ${role}'\nset service lldp interface all\nset service ssh port ${ssh_port}`;
      simNeigh = `-------------------------------------------------------------------------------\nInterface:    ${localP}, via: LLDP, RID: 1, Time: 1 day, 00:10:00\n  Chassis:\n    SysName:      ${uplinkHost}\n    SysDescr:     Managed Switch\n  Port:\n    PortID:       ifname ${remoteP}`;
    } else {
      simCfg = `! Last configuration change at ${nowIso} by netops\nversion 17.9\nservice password-encryption\nhostname ${hostname}\n!\ninterface ${localP}\n description UPLINK-TO-${uplinkHost.toUpperCase()}\n switchport mode trunk\n!\nsnmp-server community NetGuard_RO_v2c RO\nline vty 0 4\n transport input ssh\nend`;
      simNeigh = `-------------------------\nDevice ID: ${uplinkHost}.corp.local\nEntry address(es):\n  IP address: 10.10.1.1\nPlatform: Cisco Switch,  Capabilities: Switch\nInterface: ${localP},  Port ID (outgoing port): ${remoteP}`;
    }

    const created = await prisma.device.create({
      data: {
        hostname: hostname.trim(),
        ipAddress: ip_address.trim(),
        sshPort: Number(ssh_port),
        vendor,
        model,
        osType: os_type,
        role,
        site,
        credentialId: credential_id ? Number(credential_id) : null,
        isSimulated: is_simulated ? 1 : 0,
        status: 'online',
        driftDetected: 0,
        simulatedRunningConfig: simCfg,
        simulatedNeighborRaw: simNeigh,
        createdAt: nowIso,
      },
    });

    if (is_simulated) {
      await executeDeviceBackup(created.id, 'Initial Onboarding Collector');
    }

    return jsonResponse({ id: created.id, hostname: created.hostname, status: 'created' }, 201);
  } catch (err: any) {
    return errorResponse(`Could not create device: ${err.message}`, 400);
  }
}
