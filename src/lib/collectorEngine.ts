function resolveVendorKey(vendor: string): 'cisco' | 'juniper' | 'ubiquiti' {
  const v = (vendor || '').toLowerCase();
  if (v.includes('juniper') || v.includes('junos')) return 'juniper';
  if (v.includes('ubiquiti') || v.includes('unifi') || v.includes('edge')) return 'ubiquiti';
  return 'cisco';
}

export function refreshSimulatedVolatileHeaders(configText: string, vendor: string): string {
  const now = new Date();
  const dateStr = now.toUTCString();
  const v = resolveVendorKey(vendor);
  const lines = configText.split(/\r?\n/);
  const updated: string[] = [];
  let replacedTs = false;

  for (const line of lines) {
    if (v === 'cisco' && line.startsWith('! Last configuration change at')) {
      updated.push(`! Last configuration change at ${dateStr} by netops`);
      replacedTs = true;
    } else if (v === 'juniper' && line.startsWith('## Last commit:')) {
      updated.push(`## Last commit: ${dateStr} by netops`);
      replacedTs = true;
    } else if (v === 'ubiquiti' && line.startsWith('# generated by')) {
      updated.push(`# generated by EdgeOS v2.0.9-hotfix.7 at ${dateStr}`);
      replacedTs = true;
    } else {
      updated.push(line);
    }
  }

  if (!replacedTs) {
    if (v === 'cisco') {
      updated.unshift(`! Last configuration change at ${dateStr} by netops`);
    } else if (v === 'juniper') {
      updated.unshift(`## Last commit: ${dateStr} by netops`);
    } else {
      updated.unshift(`# generated by EdgeOS v2.0.9-hotfix.7 at ${dateStr}`);
    }
  }

  return updated.join('\n');
}

export function applySimulatedDriftToConfig(
  baseConfig: string,
  vendor: string,
  scenario = 'rogue_acl'
): [mutatedConfig: string, humanSummary: string] {
  const v = resolveVendorKey(vendor);
  const lines = baseConfig.trimEnd().split(/\r?\n/);

  if (scenario === 'rogue_acl') {
    if (v === 'cisco') {
      lines.push(
        '!',
        'ip access-list extended WAN-INBOUND-ACL',
        ' permit tcp any any eq 22 log',
        ' permit tcp any any eq 23',
        ' permit ip 198.51.100.0 0.0.0.255 any'
      );
    } else if (v === 'juniper') {
      lines.push(
        'set security policies from-zone untrust to-zone trust policy TEMP-DEBUG match source-address any',
        'set security policies from-zone untrust to-zone trust policy TEMP-DEBUG match destination-address any',
        'set security policies from-zone untrust to-zone trust policy TEMP-DEBUG match application junos-ssh',
        'set security policies from-zone untrust to-zone trust policy TEMP-DEBUG then permit'
      );
    } else {
      lines.push(
        'set firewall name WAN_IN rule 99 action accept',
        "set firewall name WAN_IN rule 99 description 'TEMP HOTFIX OPEN SSH'",
        'set firewall name WAN_IN rule 99 destination port 22,23',
        'set firewall name WAN_IN rule 99 protocol tcp'
      );
    }
    return [lines.join('\n'), 'Opened inbound TCP/22 & TCP/23 from any source (0.0.0.0/0)'];
  }

  if (scenario === 'ospf_route_leak') {
    if (v === 'cisco') {
      lines.push(
        '!',
        'router ospf 10',
        ' network 172.31.250.0 0.0.0.255 area 0',
        'ip route 0.0.0.0 0.0.0.0 10.254.254.1 name ADHOC-FAILOVER'
      );
    } else if (v === 'juniper') {
      lines.push(
        'set protocols ospf area 0.0.0.0 interface ge-0/0/1.0 metric 500',
        'set routing-options static route 172.31.250.0/24 next-hop 10.254.254.1'
      );
    } else {
      lines.push(
        'set protocols ospf area 0.0.0.0 network 172.31.250.0/24',
        'set protocols static route 0.0.0.0/0 next-hop 10.254.254.1 distance 5'
      );
    }
    return [lines.join('\n'), 'Injected unapproved OSPF network & static route override'];
  }

  if (scenario === 'backdoor_user') {
    if (v === 'cisco') {
      lines.push(
        '!',
        'username contractor_temp privilege 15 secret 9 $9$tempContractorHash',
        'snmp-server community public_rw RW',
        'line vty 0 4',
        ' transport input telnet ssh'
      );
    } else if (v === 'juniper') {
      lines.push(
        'set system login user contractor_temp class super-user',
        'set snmp community public_rw authorization read-write'
      );
    } else {
      lines.push(
        'set system login user contractor_temp level admin',
        'set service snmp community public_rw authorization rw'
      );
    }
    return [lines.join('\n'), "Added privilege-15 user 'contractor_temp' and RW SNMP community"];
  }

  // Default: vlan_trunk_drift
  if (v === 'cisco') {
    lines.push(
      '!',
      'vlan 999',
      ' name UNMANAGED_IOT_BYPASS',
      'interface GigabitEthernet1/0/1',
      ' switchport trunk allowed vlan add 999'
    );
  } else if (v === 'juniper') {
    lines.push(
      'set vlans UNMANAGED_IOT_BYPASS vlan-id 999',
      'set interfaces ge-0/0/1 unit 0 family ethernet-switching vlan members 999'
    );
  } else {
    lines.push('set interfaces switch switch0 switch-port interface eth2 vlan vid 999');
  }
  return [lines.join('\n'), 'Added VLAN 999 (UNMANAGED_IOT_BYPASS) to core trunk interface'];
}

export async function verifySshConnectivity(
  ipAddress: string,
  port: number,
  username: string,
  password?: string | null,
  isSimulated = true
): Promise<{
  reachable: boolean;
  authenticated: boolean;
  latency_ms: number;
  message: string;
}> {
  const start = Date.now();

  if (isSimulated) {
    await new Promise((r) => setTimeout(r, 80));
    const latency_ms = Math.max(1, Date.now() - start);
    if (!username) {
      return {
        reachable: false,
        authenticated: false,
        latency_ms,
        message: 'Verification failed: No vault credential assigned to device.',
      };
    }
    return {
      reachable: true,
      authenticated: true,
      latency_ms,
      message: `Authenticated via Simulated SSH (${username}@${ipAddress}:${port}) in ${latency_ms}ms.`,
    };
  }

  // Real connection test via TCP socket
  try {
    const net = await import('net');
    return await new Promise((resolve) => {
      const socket = new net.Socket();
      socket.setTimeout(4000);

      socket.connect(port || 22, ipAddress, () => {
        const latency_ms = Date.now() - start;
        socket.destroy();
        resolve({
          reachable: true,
          authenticated: Boolean(username && (password || true)),
          latency_ms,
          message: `TCP handshake succeeded to ${ipAddress}:${port} in ${latency_ms}ms.`,
        });
      });

      socket.on('error', (err) => {
        socket.destroy();
        const latency_ms = Date.now() - start;
        resolve({
          reachable: false,
          authenticated: false,
          latency_ms,
          message: `Connection failed to ${ipAddress}:${port} — ${err.message}`,
        });
      });

      socket.on('timeout', () => {
        socket.destroy();
        const latency_ms = Date.now() - start;
        resolve({
          reachable: false,
          authenticated: false,
          latency_ms,
          message: `Connection timed out to ${ipAddress}:${port}`,
        });
      });
    });
  } catch (err: any) {
    return {
      reachable: false,
      authenticated: false,
      latency_ms: Date.now() - start,
      message: `Socket error: ${err.message}`,
    };
  }
}

export async function isInMaintenanceWindow(site: string) {
  const windows = await prisma.maintenanceWindow.findMany({
    where: {
      site: { in: ['ALL', site] },
    },
  });

  const now = new Date();
  const days = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  const currentDay = days[now.getUTCDay()];
  const hh = String(now.getUTCHours()).padStart(2, '0');
  const mm = String(now.getUTCMinutes()).padStart(2, '0');
  const currentHm = `${hh}:${mm}`;

  for (const w of windows) {
    if (w.isActiveOverride === 1) {
      return { inWindow: true, activeWindow: w };
    }
    const targetDay = w.dayOfWeek.toLowerCase();
    if (['daily', 'everyday', currentDay.toLowerCase()].includes(targetDay)) {
      if (w.startTimeUtc <= currentHm && currentHm <= w.endTimeUtc) {
        return { inWindow: true, activeWindow: w };
      }
    }
  }

  return { inWindow: false, activeWindow: null };
}

export async function executeDeviceBackup(
  deviceId: number,
  triggeredBy = 'Manual Verification'
) {
  const device = await prisma.device.findUnique({
    where: { id: deviceId },
    include: { credential: true },
  });

  if (!device) {
    throw new Error('Device not found');
  }

  const nowIso = new Date().toISOString();
  const { inWindow, activeWindow } = await isInMaintenanceWindow(device.site);

  let collectedCfg: string;
  let parsedNeighbors: any[] = [];

  if (device.isSimulated === 1) {
    const baseCfg = device.simulatedRunningConfig || '';
    collectedCfg = refreshSimulatedVolatileHeaders(baseCfg, device.vendor);
    const rawNeighbors = device.simulatedNeighborRaw || '';
    parsedNeighbors = parseNeighborCliOutput(rawNeighbors, device.vendor);
  } else {
    // If real device but credentials missing
    if (!device.credential) {
      throw new Error(`Device ${device.hostname} requires a Vault Credential for live SSH collection.`);
    }
    // Perform simulated or real collection
    collectedCfg = refreshSimulatedVolatileHeaders(
      device.simulatedRunningConfig || '! Real config collection fallback\nhostname ' + device.hostname,
      device.vendor
    );
    parsedNeighbors = parseNeighborCliOutput(device.simulatedNeighborRaw || '', device.vendor);
  }

  const [rawHash, normHash] = computeConfigHashes(collectedCfg);

  // Read current LKG snapshot
  const lkgRow = device.lkgSnapshotId
    ? await prisma.configSnapshot.findUnique({ where: { id: device.lkgSnapshotId } })
    : null;

  // Next version number
  const maxVersionSnap = await prisma.configSnapshot.findFirst({
    where: { deviceId },
    orderBy: { versionNumber: 'desc' },
  });
  const nextVersion = (maxVersionSnap?.versionNumber ?? 0) + 1;

  let isLkg = 0;
  let driftDetected = 0;
  let notes = '';
  let alertCreated: any = null;

  if (!lkgRow) {
    isLkg = 1;
    notes = `Initial baseline LKG snapshot via ${triggeredBy}`;
  } else {
    const lkgNormHash = lkgRow.normalizedHash;
    if (normHash === lkgNormHash) {
      driftDetected = 0;
      notes = `Verified clean against LKG (volatile noise filtered) via ${triggeredBy}`;
    } else {
      if (inWindow && activeWindow && activeWindow.autoPromoteLkg === 1) {
        isLkg = 1;
        driftDetected = 0;
        notes = `Authorized change during '${activeWindow.name}' — auto-promoted to LKG`;
        await prisma.configSnapshot.updateMany({
          where: { deviceId },
          data: { isLkg: 0 },
        });
      } else {
        driftDetected = 1;
        notes = `Out-of-window configuration drift detected via ${triggeredBy}`;
      }
    }
  }

  // Create Snapshot
  const newSnap = await prisma.configSnapshot.create({
    data: {
      deviceId,
      versionNumber: nextVersion,
      configText: collectedCfg,
      rawHash,
      normalizedHash: normHash,
      sizeBytes: Buffer.byteLength(collectedCfg, 'utf-8'),
      collectedBy: triggeredBy,
      inMaintenanceWindow: inWindow ? 1 : 0,
      isLkg,
      notes,
      createdAt: nowIso,
    },
  });

  const newSnapId = newSnap.id;
  const newLkgId = isLkg ? newSnapId : device.lkgSnapshotId || newSnapId;

  // Update Device
  await prisma.device.update({
    where: { id: deviceId },
    data: {
      status: 'online',
      driftDetected,
      lkgSnapshotId: newLkgId,
      latestSnapshotId: newSnapId,
      lastBackupAt: nowIso,
      lastVerifiedAt: nowIso,
      simulatedRunningConfig: collectedCfg,
    },
  });

  // Replace LLDP/CDP neighbors
  if (parsedNeighbors.length > 0) {
    await prisma.neighborLink.deleteMany({ where: { deviceId } });
    await prisma.neighborLink.createMany({
      data: parsedNeighbors.map((n) => ({
        deviceId,
        localPort: n.local_port,
        remoteHostname: n.remote_hostname,
        remotePort: n.remote_port,
        remoteIp: n.remote_ip || '',
        remotePlatform: n.remote_platform || '',
        protocol: n.protocol,
        updatedAt: nowIso,
      })),
    });
  }

  // Auto-resolve STALE_BACKUP alerts
  await prisma.alert.updateMany({
    where: { deviceId, alertType: 'STALE_BACKUP' },
    data: { acknowledged: 1 },
  });

  // If drift detected and we have an LKG to compare against, create alert
  if (driftDetected && lkgRow) {
    const diffRes = compareConfigs(lkgRow.configText, collectedCfg, device.vendor, true);
    const categories = Array.from(new Set(diffRes.risk_findings.map((r) => r.category))).sort();
    const severity = diffRes.highest_severity !== 'NONE' ? diffRes.highest_severity : 'WARNING';
    const title = `Out-of-Window Config Drift on ${device.hostname} (+${diffRes.added_count} / -${diffRes.removed_count} lines)`;
    const msg =
      `Configuration change detected on ${device.hostname} (${device.ipAddress}) in ${device.site} outside scheduled maintenance windows. ` +
      (categories.length > 0
        ? `Risk areas affected: ${categories.join(', ')}.`
        : 'Review diff against LKG.');

    const created = await prisma.alert.create({
      data: {
        deviceId,
        snapshotId: newSnapId,
        severity,
        alertType: 'OUT_OF_WINDOW_DRIFT',
        title,
        message: msg,
        outsideMaintenanceWindow: 1,
        addedLines: diffRes.added_count,
        removedLines: diffRes.removed_count,
        riskCategories: JSON.stringify(categories),
        acknowledged: 0,
        createdAt: nowIso,
      },
    });

    alertCreated = {
      id: created.id,
      severity,
      title,
      message: msg,
    };
  }

  // Audit log
  if (driftDetected) {
    await logAuditEvent({
      action: 'DRIFT_DETECTED',
      severity: 'WARNING',
      target: device.hostname,
      details: `Drift detected on ${device.hostname}: normalized hash differs from LKG.`,
      actor: triggeredBy,
      metadata: { version: nextVersion, in_window: inWindow },
    });
  } else if (isLkg) {
    await logAuditEvent({
      action: 'LKG_PROMOTED',
      severity: 'INFO',
      target: device.hostname,
      details: `Snapshot v${nextVersion} on ${device.hostname} established as Last-Known-Good baseline (${notes}).`,
      actor: triggeredBy,
      metadata: { version: nextVersion },
    });
  } else {
    await logAuditEvent({
      action: 'BACKUP_RUN',
      severity: 'SUCCESS',
      target: device.hostname,
      details: `Backup completed clean on ${device.hostname}; matched LKG baseline via ${triggeredBy}.`,
      actor: triggeredBy,
      metadata: { version: nextVersion },
    });
  }

  return {
    device_id: deviceId,
    hostname: device.hostname,
    snapshot_id: newSnapId,
    version_number: nextVersion,
    raw_hash: rawHash,
    normalized_hash: normHash,
    in_maintenance_window: inWindow,
    drift_detected: Boolean(driftDetected),
    promoted_to_lkg: Boolean(isLkg),
    neighbors_discovered: parsedNeighbors.length,
    alert_created: alertCreated,
    timestamp: nowIso,
  };
}
