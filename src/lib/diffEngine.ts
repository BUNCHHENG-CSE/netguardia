import crypto from 'crypto';

export const VOLATILE_PATTERNS: RegExp[] = [
  /^!\s*Last configuration change at.*/i,
  /^!\s*NVRAM config last updated at.*/i,
  /^!\s*Time:.*/i,
  /^!\s*Running configuration last done at.*/i,
  /^Current configuration\s*:\s*\d+\s*bytes.*/i,
  /^Building configuration\.\.\..*/i,
  /^ntp clock-period\s+\d+.*/i,
  /^##\s*Last commit:.*/i,
  /^##\s*Last changed:.*/i,
  /^\/\*\s*Warning:\s*Do not remove.*/i,
  /^#\s*generated by.*at\s+\d{4}-\d{2}-\d{2}.*/i,
  /^!\s*uptime\s+\d+.*/i,
];

export interface RiskRule {
  severity: 'CRITICAL' | 'HIGH' | 'MEDIUM';
  category: string;
  pattern: RegExp;
}

export const RISK_RULES: RiskRule[] = [
  {
    severity: 'CRITICAL',
    category: 'Firewall / ACL Exposure',
    pattern: /\b(access-list|ip access-group|permit\s+tcp\s+any\s+any|permit\s+ip\s+any\s+any|security-zone|firewall\s+name|rule\s+\d+\s+action\s+accept)\b/i,
  },
  {
    severity: 'CRITICAL',
    category: 'Authentication / Privilege Change',
    pattern: /\b(username\s+\S+|enable\s+secret|enable\s+password|system\s+login\s+user|tacacs-server|radius-server|aaa\s+new-model|line\s+vty)\b/i,
  },
  {
    severity: 'HIGH',
    category: 'Management / Insecure Protocol',
    pattern: /\b(transport\s+input\s+telnet|ip\s+http\s+server|snmp-server\s+community\s+\S+\s+RW|snmp\s+community\s+\S+\s+authorization\s+read-write)\b/i,
  },
  {
    severity: 'HIGH',
    category: 'Routing / BGP / OSPF Policy',
    pattern: /\b(router\s+(ospf|bgp|eigrp)|ip\s+route\s+|protocols\s+(bgp|ospf)|routing-options\s+static|network\s+\d+\.\d+\.\d+\.\d+)\b/i,
  },
  {
    severity: 'MEDIUM',
    category: 'VLAN / Switching / Trunking',
    pattern: /\b(switchport\s+(mode|trunk|access)|vlan\s+\d+|spanning-tree\s+|vlans\s+\S+\s+vlan-id)\b/i,
  },
];

export function isVolatileLine(line: string): boolean {
  const stripped = line.trim();
  return VOLATILE_PATTERNS.some((p) => p.test(stripped));
}

export function normalizeConfig(configText: string, stripNoise = true): string {
  if (!configText) return '';
  const lines = configText.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n');
  const cleaned: string[] = [];

  for (const line of lines) {
    const rstripped = line.trimEnd();
    if (stripNoise && isVolatileLine(rstripped)) {
      continue;
    }
    cleaned.push(rstripped);
  }

  while (cleaned.length > 0 && cleaned[0] === '') {
    cleaned.shift();
  }
  while (cleaned.length > 0 && cleaned[cleaned.length - 1] === '') {
    cleaned.pop();
  }
  return cleaned.join('\n');
}

export function computeConfigHashes(configText: string): [rawHash: string, normHash: string] {
  const rawClean = normalizeConfig(configText, false);
  const normClean = normalizeConfig(configText, true);

  const rawHash = crypto.createHash('sha256').update(rawClean, 'utf-8').digest('hex');
  const normHash = crypto.createHash('sha256').update(normClean, 'utf-8').digest('hex');
  return [rawHash, normHash];
}

export function classifyLineRisk(line: string): { severity: string; category: string } | null {
  for (const rule of RISK_RULES) {
    if (rule.pattern.test(line)) {
      return { severity: rule.severity, category: rule.category };
    }
  }
  return null;
}

export function generateRollbackCommands(
  vendor: string,
  addedLines: string[],
  removedLines: string[]
): string[] {
  const v = (vendor || 'cisco').toLowerCase();
  const commands: string[] = [];

  if (v.includes('juniper') || v.includes('junos')) {
    commands.push('# Juniper Junos Rollback Procedure');
    commands.push('configure exclusive');
    for (const line of addedLines) {
      const clean = line.trim();
      if (clean && !clean.startsWith('#')) {
        if (clean.startsWith('set ')) {
          commands.push('delete ' + clean.slice(4));
        } else {
          commands.push(`# Remove added statement: ${clean}`);
        }
      }
    }
    for (const line of removedLines) {
      const clean = line.trim();
      if (clean && !clean.startsWith('#')) {
        if (clean.startsWith('set ')) {
          commands.push(clean);
        } else {
          commands.push(`# Restore statement: ${clean}`);
        }
      }
    }
    commands.push('commit check');
    commands.push('commit comment "Rollback to Last-Known-Good via NetGuardia"');
    return commands;
  }

  if (v.includes('ubiquiti') || v.includes('edgeos') || v.includes('unifi')) {
    commands.push('# Ubiquiti EdgeOS / UniFi CLI Rollback Procedure');
    commands.push('configure');
    for (const line of addedLines) {
      const clean = line.trim();
      if (clean && !clean.startsWith('#') && !clean.startsWith('/*')) {
        if (clean.startsWith('set ')) {
          commands.push('delete ' + clean.slice(4));
        } else {
          commands.push(`# Revert added line: ${clean}`);
        }
      }
    }
    for (const line of removedLines) {
      const clean = line.trim();
      if (clean && !clean.startsWith('#') && !clean.startsWith('/*')) {
        commands.push(clean);
      }
    }
    commands.push('commit');
    commands.push('save');
    commands.push('exit');
    return commands;
  }

  // Cisco IOS / IOS-XE / ASA default
  commands.push('! Cisco IOS/IOS-XE Rollback to Last-Known-Good (LKG)');
  commands.push('configure terminal');
  for (const line of addedLines) {
    const clean = line.trim();
    if (clean && !clean.startsWith('!')) {
      if (!clean.startsWith('no ')) {
        commands.push(`no ${clean}`);
      } else {
        commands.push(clean.slice(3));
      }
    }
  }
  for (const line of removedLines) {
    const clean = line.trim();
    if (clean && !clean.startsWith('!')) {
      commands.push(clean);
    }
  }
  commands.push('end');
  commands.push('write memory');
  return commands;
}

export interface SideBySideRow {
  type: 'unchanged' | 'added' | 'removed' | 'modified';
  left_line: number | null;
  left_text: string | null;
  right_line: number | null;
  right_text: string | null;
  risk: { severity: string; category: string } | null;
}

export interface RiskFinding {
  severity: string;
  category: string;
  line: string;
  line_number: number | null;
}

export interface CompareConfigsResult {
  has_changes: boolean;
  added_count: number;
  removed_count: number;
  suppressed_noise_lines: number;
  highest_severity: 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW' | 'NONE';
  risk_findings: RiskFinding[];
  unified_diff: string;
  side_by_side: SideBySideRow[];
  rollback_cli: string;
}

// LCS-based diff implementation to produce opcodes identical to Python's difflib.SequenceMatcher
type Opcode = ['equal' | 'delete' | 'insert' | 'replace', number, number, number, number];

function computeOpcodes(a: string[], b: string[]): Opcode[] {
  const m = a.length;
  const n = b.length;

  // Build LCS table
  // To avoid huge matrices on very large inputs, standard DP
  const dp: number[][] = Array.from({ length: m + 1 }, () => new Array(n + 1).fill(0));
  for (let i = 0; i < m; i++) {
    for (let j = 0; j < n; j++) {
      if (a[i] === b[j]) {
        dp[i + 1][j + 1] = dp[i][j] + 1;
      } else {
        dp[i + 1][j + 1] = Math.max(dp[i + 1][j], dp[i][j + 1]);
      }
    }
  }

  // Backtrack to find matching blocks
  let i = m;
  let j = n;
  const matches: Array<{ aIndex: number; bIndex: number }> = [];
  while (i > 0 && j > 0) {
    if (a[i - 1] === b[j - 1]) {
      matches.push({ aIndex: i - 1, bIndex: j - 1 });
      i--;
      j--;
    } else if (dp[i - 1][j] >= dp[i][j - 1]) {
      i--;
    } else {
      j--;
    }
  }
  matches.reverse();

  // Convert matches to opcodes
  const opcodes: Opcode[] = [];
  let aPos = 0;
  let bPos = 0;

  for (const match of matches) {
    const { aIndex, bIndex } = match;
    if (aIndex > aPos || bIndex > bPos) {
      if (aIndex > aPos && bIndex > bPos) {
        opcodes.push(['replace', aPos, aIndex, bPos, bIndex]);
      } else if (aIndex > aPos) {
        opcodes.push(['delete', aPos, aIndex, bPos, bIndex]);
      } else if (bIndex > bPos) {
        opcodes.push(['insert', aPos, aIndex, bPos, bIndex]);
      }
    }
    // equal block
    opcodes.push(['equal', aIndex, aIndex + 1, bIndex, bIndex + 1]);
    aPos = aIndex + 1;
    bPos = bIndex + 1;
  }

  if (aPos < m || bPos < n) {
    if (aPos < m && bPos < n) {
      opcodes.push(['replace', aPos, m, bPos, n]);
    } else if (aPos < m) {
      opcodes.push(['delete', aPos, m, bPos, n]);
    } else if (bPos < n) {
      opcodes.push(['insert', aPos, m, bPos, n]);
    }
  }

  // Merge consecutive identical opcodes
  const merged: Opcode[] = [];
  for (const op of opcodes) {
    if (merged.length > 0 && merged[merged.length - 1][0] === op[0]) {
      merged[merged.length - 1][2] = op[2];
      merged[merged.length - 1][4] = op[4];
    } else {
      merged.push([...op] as Opcode);
    }
  }

  return merged;
}

export function compareConfigs(
  lkgConfig: string,
  currentConfig: string,
  vendor = 'Cisco',
  ignoreNoise = true,
  lkgLabel = 'Last-Known-Good (LKG)',
  currentLabel = 'Current Config'
): CompareConfigsResult {
  const leftNorm = normalizeConfig(lkgConfig, ignoreNoise);
  const rightNorm = normalizeConfig(currentConfig, ignoreNoise);

  const rawLeftLines = normalizeConfig(lkgConfig, false).split('\n');
  const rawRightLines = normalizeConfig(currentConfig, false).split('\n');
  const suppressedNoiseCount =
    rawLeftLines.filter(isVolatileLine).length + rawRightLines.filter(isVolatileLine).length;

  const leftLines = leftNorm ? leftNorm.split('\n') : [];
  const rightLines = rightNorm ? rightNorm.split('\n') : [];

  const opcodes = computeOpcodes(leftLines, rightLines);

  const sideBySide: SideBySideRow[] = [];
  const addedLines: string[] = [];
  const removedLines: string[] = [];
  const riskFindings: RiskFinding[] = [];
  const seenRisks = new Set<string>();
  const unifiedDiffLines: string[] = [
    `--- ${lkgLabel}`,
    `+++ ${currentLabel}`,
  ];

  for (const [tag, i1, i2, j1, j2] of opcodes) {
    if (tag === 'equal') {
      for (let offset = 0; offset < i2 - i1; offset++) {
        sideBySide.push({
          type: 'unchanged',
          left_line: i1 + offset + 1,
          left_text: leftLines[i1 + offset],
          right_line: j1 + offset + 1,
          right_text: rightLines[j1 + offset],
          risk: null,
        });
        unifiedDiffLines.push(` ${leftLines[i1 + offset]}`);
      }
    } else if (tag === 'replace') {
      const leftChunk = leftLines.slice(i1, i2);
      const rightChunk = rightLines.slice(j1, j2);
      const maxLen = Math.max(leftChunk.length, rightChunk.length);

      for (const line of leftChunk) {
        removedLines.push(line);
        unifiedDiffLines.push(`-${line}`);
      }
      for (const line of rightChunk) {
        addedLines.push(line);
        unifiedDiffLines.push(`+${line}`);
      }

      for (let idx = 0; idx < maxLen; idx++) {
        const lText = idx < leftChunk.length ? leftChunk[idx] : null;
        const rText = idx < rightChunk.length ? rightChunk[idx] : null;
        const lNum = lText !== null ? i1 + idx + 1 : null;
        const rNum = rText !== null ? j1 + idx + 1 : null;

        const risk = classifyLineRisk(rText || '') || classifyLineRisk(lText || '');
        if (risk) {
          const key = `${risk.severity}|${risk.category}|${(rText || lText || '').trim()}`;
          if (!seenRisks.has(key)) {
            seenRisks.add(key);
            riskFindings.push({
              severity: risk.severity,
              category: risk.category,
              line: (rText || lText || '').trim(),
              line_number: rNum || lNum,
            });
          }
        }

        const rowType: SideBySideRow['type'] =
          lText !== null && rText !== null ? 'modified' : rText !== null ? 'added' : 'removed';

        sideBySide.push({
          type: rowType,
          left_line: lNum,
          left_text: lText,
          right_line: rNum,
          right_text: rText,
          risk,
        });
      }
    } else if (tag === 'delete') {
      for (let offset = 0; offset < i2 - i1; offset++) {
        const lText = leftLines[i1 + offset];
        const lNum = i1 + offset + 1;
        removedLines.push(lText);
        unifiedDiffLines.push(`-${lText}`);

        const risk = classifyLineRisk(lText);
        if (risk) {
          const key = `${risk.severity}|${risk.category}|${lText.trim()}`;
          if (!seenRisks.has(key)) {
            seenRisks.add(key);
            riskFindings.push({
              severity: risk.severity,
              category: risk.category,
              line: lText.trim(),
              line_number: lNum,
            });
          }
        }

        sideBySide.push({
          type: 'removed',
          left_line: lNum,
          left_text: lText,
          right_line: null,
          right_text: null,
          risk,
        });
      }
    } else if (tag === 'insert') {
      for (let offset = 0; offset < j2 - j1; offset++) {
        const rText = rightLines[j1 + offset];
        const rNum = j1 + offset + 1;
        addedLines.push(rText);
        unifiedDiffLines.push(`+${rText}`);

        const risk = classifyLineRisk(rText);
        if (risk) {
          const key = `${risk.severity}|${risk.category}|${rText.trim()}`;
          if (!seenRisks.has(key)) {
            seenRisks.add(key);
            riskFindings.push({
              severity: risk.severity,
              category: risk.category,
              line: rText.trim(),
              line_number: rNum,
            });
          }
        }

        sideBySide.push({
          type: 'added',
          left_line: null,
          left_text: null,
          right_line: rNum,
          right_text: rText,
          risk,
        });
      }
    }
  }

  const hasChanges = addedLines.length > 0 || removedLines.length > 0;
  let highestSeverity: CompareConfigsResult['highest_severity'] = 'NONE';
  if (riskFindings.some((r) => r.severity === 'CRITICAL')) {
    highestSeverity = 'CRITICAL';
  } else if (riskFindings.some((r) => r.severity === 'HIGH')) {
    highestSeverity = 'HIGH';
  } else if (riskFindings.some((r) => r.severity === 'MEDIUM')) {
    highestSeverity = 'MEDIUM';
  } else if (hasChanges) {
    highestSeverity = 'LOW';
  }

  const rollbackCli = hasChanges
    ? generateRollbackCommands(vendor, addedLines, removedLines)
    : ['# Configurations are identical — no rollback needed.'];

  return {
    has_changes: hasChanges,
    added_count: addedLines.length,
    removed_count: removedLines.length,
    suppressed_noise_lines: ignoreNoise ? suppressedNoiseCount : 0,
    highest_severity: highestSeverity,
    risk_findings: riskFindings,
    unified_diff: unifiedDiffLines.join('\n'),
    side_by_side: sideBySide,
    rollback_cli: rollbackCli.join('\n'),
  };
}
